// ชื่อยาวก่อน กัน "ແມວ" ชนะ "ແມວປ່າ"
const ANIMAL_NAME = Object.keys(ANIMAL_NAMES).sort((a, b) => b.length - a.length).join("|");
/**
 * ชื่อสัตว์ขึ้นต้นบรรทัด (คั่นกันได้หลายตัว) ตามด้วยยอด (= : ; หรือ ໂຕ / ຮູ + ตัวเลข)
 * — ต้องตามด้วยยอดทันที คำอื่นที่ขึ้นต้นเหมือนชื่อ ("ໝາກ" / "ປູ່") จึงไม่โดน
 */
const ANIMAL_LINE = new RegExp(
  String.raw`^((?:${ANIMAL_NAME})(?:\s*[,./\-\s]\s*(?:${ANIMAL_NAME}))*)\s*(?=[=:;]|(?:ໂຕ|ຕົວ|ตัว|โต|ປ່ອງ|ຮູ|รู)\s*(?:ລະ|ละ)?\s*\d)`,
  "u",
);

/** "ໄກ່=10ບລ" → "28,68=10ບລ" · "ໄກ່ ໝາ ໂຕ5" → "28,68,11,51,91 ໂຕ5" · บรรทัดอื่นคืนตามเดิม */
export function animalNamesToNumbers(text: string): string {
  const match = text.match(ANIMAL_LINE);
  if (!match) return text;
  const names = match[1]!.match(new RegExp(ANIMAL_NAME, "gu")) ?? [];
  const numbers = names.flatMap((name) => animalNumbers(ANIMAL_NAMES[name]!));
  return `${numbers.join(",")}${text.slice(match[1]!.length)}`;
}
